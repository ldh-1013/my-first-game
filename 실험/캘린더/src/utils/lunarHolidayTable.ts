export interface LunarAnchors {
  /** 설날 (음력 1월 1일) 'MM-DD' */
  seollal: string;
  /** 부처님오신날 (음력 4월 8일) 'MM-DD' */
  buddha: string;
  /** 추석 (음력 8월 15일) 'MM-DD' */
  chuseok: string;
}

/** 그 해의 음력 공휴일 양력 날짜. 표 범위를 벗어나면 null (조용히 틀린 값을 내지 않는다). */
export function getLunarAnchors(year: number): LunarAnchors | null {
  const row = TABLE[year];
  if (!row) return null;
  const at = (i: number) => `${row.slice(i, i + 2)}-${row.slice(i + 2, i + 4)}`;
  return { seollal: at(0), buddha: at(4), chuseok: at(8) };
}
