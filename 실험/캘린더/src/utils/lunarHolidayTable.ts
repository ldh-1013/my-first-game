/**
 * 음력 기반 공휴일의 양력 날짜 표 (1900~2050).
 *
 * 왜 표인가:
 * 음력→양력 변환은 순수 수식만으로는 정확해지지 않는다. 월의 대소(29/30일)와 윤달 위치는
 * 실제 삭(신월) 시각과 중기 배치로 결정되는데, 몇 분 차이로 날짜 경계가 뒤집히는 해가 있어
 * 한국천문연구원(KASI)이 확정해 둔 표를 기준으로 삼아야 한다.
 *
 * 출처:
 * MIT 라이선스의 korean-lunar-calendar 0.4.0 (usingsky/korean_lunar_calendar_js,
 * Copyright (c) 2022 Jinil Lee)의 KASI 기준 변환표로 계산해 뽑아낸 값이다.
 * 원본 라이브러리는 양력 1000-02-13 ~ 2050-12-31을 지원하지만, 이 앱에 필요한 건
 * 음력 1/1(설날)·4/8(부처님오신날)·8/15(추석) 세 날뿐이라 그 세 값만 미리 계산해 두었다.
 * 660여 개의 비트마스크 표와 변환 알고리즘을 통째로 들여오는 것보다 훨씬 작고,
 * 값이 맞는지 눈으로 검산하기도 쉽다.
 *
 * 형식: 연도 -> 'MMDD(설날) MMDD(부처님오신날) MMDD(추석)' 12자리 문자열
 */

export const LUNAR_TABLE_MIN_YEAR = 1900;
export const LUNAR_TABLE_MAX_YEAR = 2050;

/** 이 연도의 음력 공휴일을 계산할 수 있는지. 표 범위 밖이면 false. */
export function hasLunarData(year: number): boolean {
  return year >= LUNAR_TABLE_MIN_YEAR && year <= LUNAR_TABLE_MAX_YEAR;
}

